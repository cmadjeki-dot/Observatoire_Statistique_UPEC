testthat::test_that("les scores respectent orientation, ex aequo et erreurs connues", {
  source(here::here("R", "modeling", "model.R"), local = TRUE)
  y <- c(0L, 0L, 1L, 1L)
  perfect <- success_metrics(y, y)
  testthat::expect_equal(perfect$auc, 1)
  testthat::expect_equal(perfect$brier, 0)
  testthat::expect_lt(perfect$log_loss, 1e-12)
  testthat::expect_equal(success_metrics(y, 1 - y)$auc, 0)
  tied <- success_metrics(y, rep(0.5, 4))
  testthat::expect_equal(tied$auc, 0.5)
  testthat::expect_equal(tied$brier, 0.25)
  testthat::expect_equal(tied$log_loss, log(2))
  testthat::expect_true(is.na(success_metrics(c(1, 1), c(0.8, 0.9))$auc))
  testthat::expect_error(success_metrics(y, c(0, 0, 1, NA)), "invalides")
  testthat::expect_error(success_metrics(y, c(0, 0, 1, 2)), "invalides")
})

testthat::test_that("la selection, separation et estimation preservent le protocole", {
  source(here::here("R", "modeling", "model.R"), local = TRUE)
  d <- test_dataset()
  x <- dplyr::left_join(d$inscriptions, d$etudiants, by = "id_etudiant", relationship = "many-to-one")
  x <- dplyr::left_join(x, d$resultats, by = "id_inscription", relationship = "one-to-one")
  initial <- serialize(x, NULL)
  prepared <- prepare_success_model(x)
  testthat::expect_identical(serialize(x, NULL), initial)
  testthat::expect_equal(nrow(prepared$selection), 11000L)
  testthat::expect_equal(nrow(prepared$data), 10397L)
  testthat::expect_false(anyNA(prepared$data$validation))
  testthat::expect_true(all(prepared$data$annee_universitaire == "2023-2024"))
  testthat::expect_equal(sum(prepared$selection$statut == "resultat_inconnu"), 237L)
  testthat::expect_error(prepare_success_model(rbind(x, x[1, ])), "cles")
  withr::local_seed(987L)
  state <- .Random.seed
  split <- split_success_model(prepared$data)
  testthat::expect_identical(.Random.seed, state)
  testthat::expect_identical(split_success_model(prepared$data), split)
  testthat::expect_identical(split_success_model(prepared$data[nrow(prepared$data):1, ]), split)
  testthat::expect_length(intersect(split$train$id_etudiant, split$test$id_etudiant), 0L)
  testthat::expect_equal(nrow(split$train), 8316L)
  testthat::expect_equal(nrow(split$test), 2081L)
  model <- fit_success_model(split$train)
  testthat::expect_true(model$converged)
  testthat::expect_equal(model$rank, 14L)
  testthat::expect_equal(stats::nobs(model), 8316L)
  coef <- success_coefficients(model)
  testthat::expect_true(all(coef$ic95_bas < coef$odds_ratio & coef$odds_ratio < coef$ic95_haut))
  evaluation <- evaluate_success_model(model, split)
  testthat::expect_equal(evaluation$performances$n, c(2081L, 2081L))
  testthat::expect_equal(evaluation$performances$auc[2], 0.5)
  testthat::expect_equal(sum(evaluation$calibration$n), 2081L)
  testthat::expect_setequal(evaluation$predictions_test$id_etudiant, split$test$id_etudiant)
  leak <- split
  leak$test$id_etudiant[1] <- split$train$id_etudiant[1]
  testthat::expect_error(evaluate_success_model(model, leak), "Fuite")
  diagnostics <- diagnose_success_model(model, split$train)
  testthat::expect_equal(sum(diagnostics$detail$levier), 14, tolerance = 1e-6)
  testthat::expect_equal(nrow(diagnostics$detail), 8316L)
  path <- fs::path(withr::local_tempdir(), "model.rds")
  saveRDS(model, path)
  testthat::expect_equal(as.numeric(stats::predict(readRDS(path), split$test, type = "response")),
    evaluation$predictions_test$probabilite)
})
